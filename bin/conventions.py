def _check_file(
    fpath: Path, name: str, schema: dict, repo_root: Path
) -> list[str]:
    """Check one convention file against its schema. Returns list of issues."""
    issues = []
    if not fpath.exists():
        if schema.get("must_exist") is False:
            return issues  # optional, skip
        issues.append(f"MISSING: {fpath.relative_to(repo_root)} — {schema['description']}")
        return issues

    # Skip section checks for files that are clearly redirects (e.g. CLAUDE.md
    # that points to AGENTS.md in some repos).
    content = fpath.read_text()
    if schema.get("required_sections"):
        if "See **`AGENTS.md`**" in content or len(content) < 200:
            return issues

    # Check required sections — must appear as a markdown heading (## or ###).
    # This prevents false positives from a single-hash header or inline text.
    for section in schema.get("required_sections", []):
        pattern = re.compile(r"^#{2,3}\s+" + re.escape(section), re.MULTILINE | re.IGNORECASE)
        if not pattern.search(content):
            issues.append(
                f"MISSING SECTION in {fpath.relative_to(repo_root)}: '{section}'"
            )

    # Check frontmatter (if present)
    if content.startswith("---"):
        end = content.index("---", 3)
        fm = content[3:end]
        for key in schema.get("required_keys", []):
            if key not in fm:
                issues.append(
                    f"MISSING frontmatter key '{key}' in {fpath.relative_to(repo_root)}"
                )

    return issues


def cmd_check(repo_path: str | None) -> int:
    """Check a repo's convention files against the schema."""
    repo = Path(repo_path) if repo_path else Path.cwd()
    if not repo.is_dir():
        print(f"ERROR: {repo} is not a directory", file=sys.stderr)
        return 1

    all_issues: list[str] = []
    total = 0

    for name, schema in SCHEMA.items():
        fpath = repo / name
        issues = _check_file(fpath, name, schema, repo)
        total += 1
        all_issues.extend(issues)

    if all_issues:
        print(f"Drift check found {len(all_issues)} issue(s) in {repo}:")
        for issue in all_issues:
            print(f"  - {issue}")
        return 1
    else:
        print(f"OK: {total} convention file(s) checked, no drift detected")
        return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Conventions tier: scaffold + drift check for repo-shape files"
    )
    sub = parser.add_subparsers(dest="command")

    s = sub.add_parser("scaffold", help="Scaffold conventional files into target dir")
    s.add_argument("target", help="Target directory to scaffold into")

    c = sub.add_parser("check", help="Check convention files against schema")
    c.add_argument("--repo", default=None, help="Path to repo root (default: cwd)")

    args = parser.parse_args()
    if not args.command:
        parser.print_help()
        return 0

    if args.command == "scaffold":
        return cmd_scaffold(args.target)
    elif args.command == "check":
        return cmd_check(args.repo)
    return 1


if __name__ == "__main__":
    sys.exit(main())
