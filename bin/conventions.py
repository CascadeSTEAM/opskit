#!/usr/bin/env python3
"""Conventions tier: scaffold + drift check for repo-shape files.

Sibling projects keep reinventing the same repo-shape files
(AGENTS.md/CLAUDE.md, .opencode/ and .claude/ harness dirs, .githooks/,
SESSION-LOG.md lifecycle). The *content* legitimately differs per project,
so "one shared skills directory" is the wrong answer. What is shared is
the **shape** — required sections, frontmatter structure, lifecycle rules.

This tool provides:
  scaffold <target_dir>    — emit conventional files with correct structure
  check [--repo PATH]      — report missing sections, structural drift

Designed after the reuse contract (docs/reuse-contract.md): skills and
content are never shared, only the scaffolding shape.
"""

